/** Add only the three curated examples; never replace an existing published slug. */
import {createClient,createAdminClient} from '@insforge/sdk';
import {readFile,writeFile} from 'node:fs/promises';
import vm from 'node:vm';
const baseUrl=process.env.NEXT_PUBLIC_INSFORGE_URL;
const client=createClient({baseUrl,anonKey:process.env.NEXT_PUBLIC_INSFORGE_ANON_KEY});
const checked=r=>{if(r.error)throw new Error(r.error.message);return r.data;};
const auth=checked(await client.auth.signInWithPassword({email:process.env.DEMO_EMAIL,password:process.env.DEMO_PASSWORD}));
const db=createAdminClient({baseUrl,apiKey:process.env.INSFORGE_API_KEY}).database;
const records=[];
for(const [slug,title] of [['daily-habits','Daily Habits'],['recipe-collection','The Recipe Shelf'],['studio-open-day','Studio Open Day']]){
 const existing=checked(await db.from('projects').select('id,published_version_id').eq('published_slug',slug).maybeSingle());
 if(existing){records.push({slug,title,projectId:existing.id,versionId:existing.published_version_id,existing:true});continue;}
 const files=Object.fromEntries(await Promise.all(['index.html','style.css','app.js'].map(async name=>[name,await readFile(`examples/${slug}/${name}`,'utf8')])));
 new vm.Script(files['app.js']);
 for(const [name,text] of Object.entries(files))if(Buffer.byteLength(text)>100000)throw Error('File too large: '+name);
 if(!files['index.html'].includes('href="style.css"')||!files['index.html'].includes('src="app.js"'))throw Error('Missing local resource');
 const project=checked(await db.from('projects').insert([{owner_id:auth.user.id,title}]).select('id').single());
 const version=checked(await db.from('versions').insert([{project_id:project.id,number:1,files,summary:'Curated starter template'}]).select('id').single());
 checked(await db.from('messages').insert([{project_id:project.id,role:'system',content:'Curated starter template prepared for the example library. This snapshot was authored as a template, not generated by a recorded AI run.',version_id:version.id,meta:{kind:'starter-template'}}]));
 checked(await db.from('projects').update({current_version_id:version.id,published_version_id:version.id,published_slug:slug}).eq('id',project.id));
 records.push({slug,title,projectId:project.id,versionId:version.id,existing:false});
}
await writeFile('.insforge/starter-examples.json',JSON.stringify(records,null,2));
console.log(JSON.stringify(records,null,2));
